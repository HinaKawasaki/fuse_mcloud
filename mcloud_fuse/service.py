"""``systemd --user`` 服务管理（安装 / 卸载 / 状态）。

服务单元完全由用户配置生成，不再依赖 shell 模板与 ``EnvironmentFile``：
挂载点、缓存目录、云盘范围（路径或 fileId）都在 ``config.json`` 里，``mcloud-fuse mount``
启动时自己读取，单元里只需要固定解释器与配置文件路径。

每个用户一个账号、一个服务、一个挂载点；不启用 ``allow_other``，因此不需要
root，也不需要修改 ``/etc/fuse.conf``。
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Optional, Sequence

from mcloud_fuse.userconfig import UserConfig, config_path, default_token_path

UNIT_NAME = "mcloud-fuse.service"
_MARKER = "# Generated by `mcloud-fuse setup`; edits will be overwritten.\n"


def unit_dir() -> Path:
    override = os.getenv("MCLOUD_SYSTEMD_USER_DIR")
    if override:
        return Path(override).expanduser()
    return Path.home() / ".config" / "systemd" / "user"


def unit_path() -> Path:
    return unit_dir() / UNIT_NAME


def available() -> bool:
    return shutil.which("systemctl") is not None


def _sd_quote(value: str) -> str:
    """systemd 单元里的参数引用：含空白或引号时加双引号并转义。"""
    text = str(value).replace("%", "%%")
    if not text or any(char.isspace() for char in text) or '"' in text or "\\" in text:
        escaped = text.replace("\\", "\\\\").replace('"', '\\"')
        return f'"{escaped}"'
    return text


def render_unit(
    config: UserConfig,
    *,
    python: Optional[str] = None,
    config_file: Optional[Path] = None,
    token_file: Optional[Path] = None,
) -> str:
    python_bin = python or sys.executable
    cfg_file = config_file or config_path()
    token = token_file or default_token_path()
    fusermount = shutil.which("fusermount3") or "/bin/fusermount3"
    return (
        _MARKER
        + "[Unit]\n"
        + "Description=MCloud FUSE mount (中国移动云盘，用户级)\n"
        + "After=network-online.target\n"
        + "Wants=network-online.target\n"
        + "StartLimitIntervalSec=60\n"
        + "StartLimitBurst=5\n"
        + "\n"
        + "[Service]\n"
        + "Type=notify\n"
        + "NotifyAccess=main\n"
        + "Environment=PYTHONUNBUFFERED=1\n"
        + f"Environment=MCLOUD_CONFIG_FILE={_sd_quote(str(cfg_file))}\n"
        + f"Environment=MCLOUD_WEB_TOKEN_FILE={_sd_quote(str(token))}\n"
        + f"ExecStart={_sd_quote(python_bin)} -m mcloud_fuse mount\n"
        + f"ExecStop=-{_sd_quote(fusermount)} -u {_sd_quote(config.mountpoint)}\n"
        + "Restart=on-failure\n"
        # 关机抢救默认预算 20s + 删除队列/卸载收尾；给足余量但不要无限等。
        + "TimeoutStartSec=60\n"
        + "TimeoutStopSec=60\n"
        + "RestartSec=5\n"
        + "\n"
        + "[Install]\n"
        + "WantedBy=default.target\n"
    )


def write_unit(config: UserConfig, path: Optional[Path] = None) -> Path:
    target = path or unit_path()
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_unit(config), encoding="utf-8")
    target.chmod(0o644)
    return target


@dataclass(frozen=True)
class ServiceResult:
    ok: bool
    detail: str


def _run(args: Sequence[str], timeout: float = 30.0) -> subprocess.CompletedProcess:
    return subprocess.run(
        list(args),
        check=False,
        capture_output=True,
        text=True,
        timeout=timeout,
    )


def _tail(result: subprocess.CompletedProcess) -> str:
    text = (result.stderr or result.stdout or "").strip()
    if not text:
        return f"systemctl 退出码 {result.returncode}"
    return text.splitlines()[-1]


def is_active() -> bool:
    if not available():
        return False
    try:
        result = _run(["systemctl", "--user", "is-active", UNIT_NAME], timeout=10)
    except (OSError, subprocess.TimeoutExpired):
        return False
    return result.returncode == 0 and result.stdout.strip() == "active"


def status_text() -> str:
    if not unit_path().exists():
        return "未安装"
    if not available():
        return "已安装（当前环境没有 systemctl）"
    return "运行中" if is_active() else "已安装，未运行"


def install(config: UserConfig) -> ServiceResult:
    """写单元并 ``enable --now``；返回可展示的结果。"""
    if not available():
        return ServiceResult(False, "找不到 systemctl，无法安装用户服务")
    try:
        path = write_unit(config)
    except OSError as exc:
        return ServiceResult(False, f"写入服务单元失败：{exc}")

    try:
        reload_result = _run(["systemctl", "--user", "daemon-reload"])
        if reload_result.returncode != 0:
            return ServiceResult(False, f"daemon-reload 失败：{_tail(reload_result)}")
        enable_result = _run(["systemctl", "--user", "enable", "--now", UNIT_NAME], timeout=90)
        if enable_result.returncode != 0:
            return ServiceResult(False, f"启动服务失败：{_tail(enable_result)}")
    except (OSError, subprocess.TimeoutExpired) as exc:
        return ServiceResult(False, f"调用 systemctl 失败：{exc}")

    # 给 FUSE 一点启动时间，便于在向导里直接报告「已挂载」
    for _ in range(10):
        if is_active() and os.path.ismount(config.mountpoint):
            break
        time.sleep(0.3)
    detail = f"服务已安装并启动：{path}"
    if not os.path.ismount(config.mountpoint):
        detail += "（进程已启动，挂载点尚未就绪；稍后用 `mcloud-fuse status` 确认）"
    return ServiceResult(True, detail)


def uninstall() -> ServiceResult:
    if not available():
        return ServiceResult(False, "找不到 systemctl")
    try:
        _run(["systemctl", "--user", "disable", "--now", UNIT_NAME], timeout=60)
    except (OSError, subprocess.TimeoutExpired) as exc:
        return ServiceResult(False, f"停止服务失败：{exc}")
    path = unit_path()
    if path.exists():
        try:
            path.unlink()
        except OSError as exc:
            return ServiceResult(False, f"删除服务单元失败：{exc}")
    try:
        _run(["systemctl", "--user", "daemon-reload"])
    except (OSError, subprocess.TimeoutExpired):
        pass
    return ServiceResult(True, "用户服务已卸载")


def stop() -> ServiceResult:
    if not available():
        return ServiceResult(False, "找不到 systemctl")
    try:
        result = _run(["systemctl", "--user", "stop", UNIT_NAME], timeout=60)
    except (OSError, subprocess.TimeoutExpired) as exc:
        return ServiceResult(False, f"停止服务失败：{exc}")
    if result.returncode != 0:
        return ServiceResult(False, _tail(result))
    return ServiceResult(True, "服务已停止")
